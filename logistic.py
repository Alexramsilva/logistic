# OPTIMIZACIÓN CON PuLP
# =========================================================
def optimizar_distribucion(
    demanda,
    capacidades,
    congestion_pct,
    penalizacion,
    costo_km
):
    n_v = len(VEHICULOS)
    n_z = len(ZONAS)

    # Costo variable por unidad: viaje redondo estimado.
    factor_congestion = 1 + congestion_pct / 100

    costo_unitario = np.zeros((n_v, n_z))
    costo_visita = np.zeros((n_v, n_z))

    for v in range(n_v):
        for z in range(n_z):
            km_redondo = 2 * DISTANCIAS[z]

            costo_unitario[v, z] = (
                km_redondo * costo_km
                * FACTORES_VEHICULO[v]
                * factor_congestion
            )

            # Costo fijo estimado por visita a una zona.
            costo_visita[v, z] = (
                25 * FACTORES_VEHICULO[v]
                * factor_congestion
            )

    problema = pulp.LpProblem(
        "Distribucion_Ultima_Milla",
        pulp.LpMinimize
    )

    # x[v,z]: unidades enteras enviadas.
    x = {
        (v, z): pulp.LpVariable(
            f"x_{v}_{z}", lowBound=0, cat=pulp.LpInteger
        )
        for v in range(n_v)
        for z in range(n_z)
    }

    # y[v,z]: 1 si el vehículo visita la zona.
    y = {
        (v, z): pulp.LpVariable(
            f"visita_{v}_{z}", cat=pulp.LpBinary
        )
        for v in range(n_v)
        for z in range(n_z)
    }

    # a[v]: 1 si el vehículo se utiliza.
    a = {
        v: pulp.LpVariable(
            f"activo_{v}", cat=pulp.LpBinary
        )
        for v in range(n_v)
    }

    # u[z]: demanda no atendida.
    u = {
        z: pulp.LpVariable(
            f"faltante_{z}", lowBound=0, cat=pulp.LpInteger
        )
        for z in range(n_z)
    }

    # Objetivo: costo variable + visitas + faltantes.
    problema += (
        pulp.lpSum(
            costo_unitario[v, z] * x[v, z]
            + costo_visita[v, z] * y[v, z]
            for v in range(n_v)
            for z in range(n_z)
        )
        + penalizacion * pulp.lpSum(u[z] for z in range(n_z))
    )

    # Capacidad de cada vehículo.
    for v in range(n_v):
        problema += (
            pulp.lpSum(x[v, z] for z in range(n_z))
            <= int(capacidades[v]) * a[v]
        )

        for z in range(n_z):
            problema += y[v, z] <= a[v]

            # Solo se puede entregar en una zona si se visita.
            problema += (
                x[v, z] <= int(demanda[z]) * y[v, z]
            )

    # Cada pedido debe entregarse o quedar como faltante.
    for z in range(n_z):
        problema += (
            pulp.lpSum(x[v, z] for v in range(n_v))
            + u[z] == int(demanda[z])
        )

    problema.solve(pulp.PULP_CBC_CMD(msg=False))

    if pulp.LpStatus[problema.status] != "Optimal":
        raise RuntimeError(
            "No se encontró una solución óptima. "
            f"Estado: {pulp.LpStatus[problema.status]}"
        )

    plan = np.array([
        [
            int(round(pulp.value(x[v, z]) or 0))
            for z in range(n_z)
        ]
        for v in range(n_v)
    ])

    visitas = np.array([
        [
            int(round(pulp.value(y[v, z]) or 0))
            for z in range(n_z)
        ]
        for v in range(n_v)
    ])

    usados = np.array([
        int(round(pulp.value(a[v]) or 0))
        for v in range(n_v)
    ])

    faltantes = np.array([
        int(round(pulp.value(u[z]) or 0))
        for z in range(n_z)
    ])

    costo_variable_real = float(sum(
        costo_unitario[v, z] * plan[v, z]
        for v in range(n_v)
        for z in range(n_z)
    ))

    costo_fijo_real = float(sum(
        costo_visita[v, z] * visitas[v, z]
        for v in range(n_v)
        for z in range(n_z)
    ))

    costo_penalizacion = float(
        penalizacion * faltantes.sum()
    )

    return {
        "plan": plan,
        "visitas": visitas,
        "vehiculos_usados": usados,
        "faltantes": faltantes,
        "costo_variable": costo_variable_real,
        "costo_fijo": costo_fijo_real,
        "costo_penalizacion": costo_penalizacion,
        "costo_total": (
            costo_variable_real
            + costo_fijo_real
            + costo_penalizacion
        ),
        "costo_unitario": costo_unitario
    }


