@st.cache_data
def generar_historico():
    rng = np.random.default_rng(42)
    filas = []

    demanda_base = [34, 42, 31, 37]

    for dia in range(210):
        for j, zona in enumerate(ZONAS):
            dia_semana = dia % 7
            promocion = int(rng.random() < 0.22)

            fin_semana = int(dia_semana in [5, 6])
            tendencia = 0.035 * dia
            estacionalidad = (
                5 * np.sin(2 * np.pi * dia_semana / 7)
            )

            demanda = (
                demanda_base[j]
                + tendencia
                + estacionalidad
                + 9 * promocion
                + 4 * fin_semana
                + rng.normal(0, 4)
            )

            filas.append({
                "dia": dia,
                "dia_semana": dia_semana,
                "zona": zona,
                "zona_id": j,
                "promocion": promocion,
                "demanda": max(1, int(round(demanda)))
            })

    return pd.DataFrame(filas)


