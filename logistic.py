# VARIABLES EXPLICATIVAS DE LA RED NEURONAL
# =========================================================
def construir_X(df):
    dia = df["dia"].to_numpy(dtype=float)
    ds = df["dia_semana"].to_numpy(dtype=float)
    zona = df["zona_id"].to_numpy(dtype=int)
    promo = df["promocion"].to_numpy(dtype=float)

    return np.column_stack([
        dia,
        np.sin(2 * np.pi * ds / 7),
        np.cos(2 * np.pi * ds / 7),
        promo,
        (zona == 0).astype(float),
        (zona == 1).astype(float),
        (zona == 2).astype(float),
        (zona == 3).astype(float)
    ])


