def entrenar_mlp(df, neuronas, iteraciones):
    # Separación temporal: primeros 180 días para entrenar.
    train = df[df["dia"] < 180]
    test = df[df["dia"] >= 180]

    modelo = make_pipeline(
        StandardScaler(),
        MLPRegressor(
            hidden_layer_sizes=(neuronas, max(4, neuronas // 2)),
            activation="relu",
            solver="adam",
            max_iter=iteraciones,
            early_stopping=True,
            validation_fraction=0.15,
            n_iter_no_change=25,
            random_state=42
        )
    )

    modelo.fit(
        construir_X(train),
        train["demanda"].to_numpy()
    )

    pred_test = np.maximum(
        0, modelo.predict(construir_X(test))
    )

    mae = mean_absolute_error(
        test["demanda"].to_numpy(), pred_test
    )

    return modelo, mae, test, pred_test


def pronosticar(modelo, dia, promociones):
    filas = []

    for j, zona in enumerate(ZONAS):
        fila = pd.DataFrame([{
            "dia": dia,
            "dia_semana": dia % 7,
            "zona": zona,
            "zona_id": j,
            "promocion": int(promociones[j])
        }])

        pred = float(
            modelo.predict(construir_X(fila))[0]
        )

        filas.append({
            "Zona": zona,
            "Demanda estimada": max(0, int(np.ceil(pred)))
        })

    return pd.DataFrame(filas)


