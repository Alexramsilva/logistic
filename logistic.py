def mostrar_metricas(sol, demanda):
    total_demanda = int(np.sum(demanda))
    total_entregado = int(sol["plan"].sum())
    faltantes = int(sol["faltantes"].sum())

    servicio = (
        100 * total_entregado / total_demanda
        if total_demanda > 0 else 100
    )

    a, b, c, d = st.columns(4)
    a.metric("Demanda", f"{total_demanda:,} unidades")
    b.metric("Entregado", f"{total_entregado:,} unidades")
    c.metric("Faltantes", f"{faltantes:,} unidades")
    d.metric("Nivel de servicio", f"{servicio:.1f}%")

    e, f, g = st.columns(3)
    e.metric("Costo variable", f"${sol['costo_variable']:,.2f}")
    f.metric("Costo fijo de visitas", f"${sol['costo_fijo']:,.2f}")
    g.metric("Costo logístico total", f"${sol['costo_total']:,.2f}")


def mostrar_plan(sol):
    plan = pd.DataFrame(
        sol["plan"], index=VEHICULOS, columns=ZONAS
    )

    st.subheader("Asignación de pedidos")
    st.dataframe(plan, use_container_width=True)

    fig = px.imshow(
        plan,
        text_auto=True,
        aspect="auto",
        title="Unidades asignadas por vehículo y zona",
        labels={"x": "Zona", "y": "Vehículo", "color": "Unidades"}
    )
    fig.update_layout(template="plotly_dark")
    st.plotly_chart(fig, use_container_width=True)

    uso = pd.DataFrame({
        "Vehículo": VEHICULOS,
        "Unidades asignadas": sol["plan"].sum(axis=1),
        "Capacidad": CAPACIDADES,
        "Vehículo utilizado": sol["vehiculos_usados"]
    })

    uso["Utilización (%)"] = np.where(
        uso["Capacidad"] > 0,
        100 * uso["Unidades asignadas"] / uso["Capacidad"],
        0
    )

    st.subheader("Utilización de la flota")
    st.dataframe(uso.round(2), hide_index=True)

    faltantes_df = pd.DataFrame({
        "Zona": ZONAS,
        "Demanda no atendida": sol["faltantes"]
    })

    st.subheader("Pedidos no atendidos por zona")
    st.dataframe(faltantes_df, hide_index=True)

    return plan


